export function serviceGroup(key) {
  return GROUP_MAP[key] || "Other";
}

export function groupedServices(services) {
  const groups = {};
  (services || []).forEach((item) => {
    const group = serviceGroup(item.key || item.id);
    if (!groups[group]) groups[group] = [];
    groups[group].push(item);
  });
  return groups;
}
